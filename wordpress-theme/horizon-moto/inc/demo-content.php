/**
 * One-time import of the original site's content when the theme is first activated.
 * Re-running is safe: anything that already exists is skipped.
 */
add_action( 'after_switch_theme', 'hm_import_demo_content' );

function hm_import_demo_content() {
	if ( get_option( 'hm_demo_imported' ) || ! current_user_can( 'manage_options' ) ) {
		return;
	}
	$data = hm_demo_data();

	// Pages.
	$page_ids = array();
	foreach ( $data['pages'] as $key => $page ) {
		$existing = get_page_by_path( $page['slug'] );
		if ( $existing ) {
			$page_ids[ $key ] = $existing->ID;
			continue;
		}
		$meta = array();
		foreach ( $page['meta'] as $k => $v ) {
			$meta[ '_hm_' . $k ] = $v;
		}
		$page_ids[ $key ] = wp_insert_post( array(
			'post_type'     => 'page',
			'post_status'   => isset( $page['status'] ) ? $page['status'] : 'publish',
			'post_title'    => $page['title'],
			'post_name'     => $page['slug'],
			'post_content'  => $page['content'],
			'page_template' => $page['template'],
			'meta_input'    => $meta,
		) );
	}
	update_option( 'show_on_front', 'page' );
	update_option( 'page_on_front', $page_ids['home'] );
	update_option( 'page_for_posts', $page_ids['blog'] );

	// Tours, routes, guides, passes.
	$types = array( 'tours' => 'hm_tour', 'routes' => 'hm_route', 'guides' => 'hm_guide', 'passes' => 'hm_pass' );
	foreach ( $types as $key => $post_type ) {
		$has_any = get_posts( array( 'post_type' => $post_type, 'post_status' => 'any', 'posts_per_page' => 1, 'fields' => 'ids' ) );
		if ( $has_any ) {
			continue;
		}
		foreach ( $data[ $key ] as $i => $item ) {
			wp_insert_post( array(
				'post_type'   => $post_type,
				'post_status' => 'publish',
				'post_title'  => $item['title'],
				'post_name'   => isset( $item['slug'] ) ? $item['slug'] : '',
				'menu_order'  => $i,
				'meta_input'  => hm_demo_meta( $item['meta'], 'routes' === $key ? 1200 : 900 ),
			) );
		}
	}

	// Blog articles (only if the site has no posts besides the default "Hello world!").
	$post_count = (int) wp_count_posts( 'post' )->publish;
	if ( $post_count <= 1 ) {
		foreach ( array_reverse( $data['posts'] ) as $i => $item ) {
			$cat = term_exists( $item['category'], 'category' );
			if ( ! $cat ) {
				$cat = wp_insert_term( $item['category'], 'category' );
			}
			wp_insert_post( array(
				'post_type'     => 'post',
				'post_status'   => 'publish',
				'post_title'    => $item['title'],
				'post_excerpt'  => $item['excerpt'],
				'post_content'  => '<!-- wp:paragraph --><p>' . esc_html( $item['excerpt'] ) . '</p><!-- /wp:paragraph -->',
				'post_category' => is_wp_error( $cat ) ? array() : array( (int) $cat['term_id'] ),
				'post_date'     => gmdate( 'Y-m-d H:i:s', time() - ( count( $data['posts'] ) - $i ) * DAY_IN_SECONDS ),
				'meta_input'    => hm_demo_meta( $item['meta'], 900 ),
			) );
		}
		$hello = get_page_by_path( 'hello-world', OBJECT, 'post' );
		if ( $hello ) {
			wp_trash_post( $hello->ID );
		}
	}

	// Main menu.
	$locations = get_theme_mod( 'nav_menu_locations', array() );
	if ( empty( $locations['primary'] ) && ! wp_get_nav_menu_object( 'Main menu' ) ) {
		$menu_id = wp_create_nav_menu( 'Main menu' );
		if ( ! is_wp_error( $menu_id ) ) {
			$labels = array( 'tours' => 'Tours', 'booking' => 'Booking', 'blog' => 'Blog', 'guides' => 'Guides', 'suggest' => 'Suggest a Ride' );
			foreach ( $labels as $key => $label ) {
				wp_update_nav_menu_item( $menu_id, 0, array(
					'menu-item-title'     => $label,
					'menu-item-object'    => 'page',
					'menu-item-object-id' => $page_ids[ $key ],
					'menu-item-type'      => 'post_type',
					'menu-item-status'    => 'publish',
				) );
			}
			$locations['primary'] = $menu_id;
			set_theme_mod( 'nav_menu_locations', $locations );
		}
	}

	// Pretty links (needed for /route/... pages) if the site still uses the default "Plain" setting.
	if ( '' === get_option( 'permalink_structure' ) ) {
		update_option( 'permalink_structure', '/%postname%/' );
	}
	flush_rewrite_rules();

	update_option( 'hm_demo_imported', 1 );
	set_transient( 'hm_demo_notice', 1, MINUTE_IN_SECONDS * 10 );
}

/** Convert demo meta to _hm_ keys; "photo" becomes a stock image URL. */
function hm_demo_meta( $meta, $width ) {
	$out = array();
	foreach ( $meta as $k => $v ) {
		if ( 'photo' === $k ) {
			$out['_hm_image_url'] = hm_stock_photo( $v, $width );
		} else {
			$out[ '_hm_' . $k ] = $v;
		}
	}
	return $out;
}

